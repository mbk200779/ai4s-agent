"""
长文档解析的硬性上限。

为什么所有数字都集中在这个文件里：
解析 541 页教材时，内存不是"慢慢涨"而是"某一页突然爆"，爆点几乎都来自
某个没有上限的累加器（页面图列表、全文拼接、批量 embedding）。
把这些数字写成模块常量后，任何一个新加的循环都必须显式说明自己的上限，
review 时能一眼看出谁在偷偷全量持有数据。

改这里的值时请连带更新 docs/2.7-异步解析与长文档.md 的实测表。
"""

import os

# ---------- 输入约束 ----------
# 单个 PDF 的字节上限。超过直接拒收，避免把对象存储和临时盘当无限缓冲。
MAX_PDF_BYTES = 512 * 1024 * 1024  # 512 MiB

# 单文档页数上限。541 页教材远低于这个值；设上限是为了挡住恶意构造的
# "几万页空页" PDF —— 那种文件字节很小但逐页渲染会跑到天荒地老。
MAX_PAGES = 3000

# ---------- 分批策略 ----------
# 一个批次 = 一次解析 + 一次向量入库 + 一次 SQLite 提交 + 一次进度落盘。
# 30 页时单批 embedding 约 400 条，CPU 上要十几秒，进度条会显得卡；
# 20 页把单批压到 ~250 条，进度更细，断点粒度也更小。
PAGES_PER_BATCH = 20

# 单批片段数上限。整页都是密集表格时页数不能代表工作量，
# 片段数才是内存真正的自变量，所以再加一道闸。
MAX_FRAGMENTS_PER_BATCH = 600

# 单页正文截断长度。扫描版 PDF 偶尔会把整页 OCR 成一坨，
# 单页 12 万字符已经远超正常教材（约 3000 字符/页）。
MAX_TEXT_CHARS_PER_PAGE = 120_000

# ---------- 累积型数据的上限 ----------
# 参考文献原文是跨批次累积的（References 在文末），这是唯一一个
# 无法按批释放的大对象，所以必须设上限。40 万字符约等于 1000 条文献。
MAX_REFERENCE_CHARS = 400_000
# 标题列表同样跨批累积，但每条只有几十字符，5000 条是安全上限。
MAX_HEADINGS = 5000
# 引用位置扫描按 chunk 分窗，避免把整本正文一次性读进内存。
CITATION_SCAN_CHUNKS = 2000

# ---------- 渲染与视觉模型 ----------
# 送去 embedding 的最大字符数。
#
# 实测（16 核 CPU、multilingual-e5-large fp32）：
#   500 字符 × 20 条 → 6.0s
#   2662 字符 × 20 条 → 30.0s
# 也就是说 fastembed 不做 512-token 截断，耗时与字符数线性相关；
# 而 e5-large 的有效上下文就是 512 token（约 1500 字符），超出的部分
# 既不会进入语义表示，又会实打实地烧 CPU。所以入库前先截到 1500 字符：
# 向量质量与"模型自己截断"完全一致，耗时按最长的正文块算也降一半以上。
# 注意：截断只影响送进模型的输入，chunks.text 仍然存完整原文，溯源不受影响。
MAX_EMBED_CHARS = 1500

# 页面图 DPI。150 时 A4 页约 1.4MB PNG，541 页就是 750MB 的临时流量；
# 110 足够前端缩略图与溯源高亮使用，体积降到约 0.6MB/页。
RENDER_DPI = 110
# 是否渲染页面图。关掉可省掉全部页面图 I/O，但前端溯源就没法高亮原页。
RENDER_PAGE_IMAGES = True

# 视觉模型调用的硬预算：每本文档最多这么多次。
# 图表/公式的 vision 调用是整条链里唯一按"张"计费且秒级的地方，
# 541 页教材有几百张图，不设预算会跑成几小时并烧掉一笔钱。
MAX_VISION_CALLS_PER_DOC = 40
# 超过这个页数就默认只保留 caption、关闭 vision（除非显式传 allow_vision）。
# 短论文（<80 页）视觉信息价值高，值得花；教材的图注大多自带文字说明。
LONG_DOC_PAGES = 80

# ---------- 进程资源 ----------
# worker 进程 RSS 软上限（MiB）。
#
# 这里必须说清楚"基线"和"文档预算"的区别：multilingual-e5-large 是 560M 参数的
# fp32 模型，fastembed 常驻后单个子进程 RSS 就已经约 2.6GB（实测 2903MB 时
# 才解析到第 20 页，其中约 2.6GB 是模型本身）。所以：
#   软上限 4096MB - 模型基线 ~2600MB ≈ 1400MB 留给单本文档
# 对 541 页、按 20 页一批的流式解析来说，1400MB 的余量非常宽裕。
# 超限就主动失败并保留上下文，而不是等内核 OOM Killer 无声杀掉进程。
# 如果换了更大的 embedding 模型，这个值要跟着抬，否则每本书都会"超限失败"。
#
# 为什么改成可被环境变量覆盖（2026-11-11）：
# 上面那条预算的前提是"机器只有 8GB"。换到 16GB 机器后，两篇论文的单篇峰值
# 都已越过 4096：BERT（16 页 / 58 片段）4512MB、ViT（22 页 / 82 片段）6093MB。
# 要注意这不是"多篇累积"——celery_app 里 worker_max_tasks_per_child=1 已经
# 保证每篇都在同一基线上起跑，超限发生在**单篇内部**的 structuring 阶段，
# 图片多的论文把片段和渲染图同时留在内存里，峰值就到这个量级。
# 所以这个值本身没有对错，只有"和运行机器的内存配不配"：
#   INGEST_RSS_SOFT_LIMIT_MB 未设置 → 保持 4096（8GB 机器的保守默认）
#   16GB 机器建议 7168：实测峰值 6093，留约 1GB 余量，仍远低于物理内存，
#   OOM Killer 依然够不到（worker 7168 + api 约 2600 < 15GB）。
RSS_SOFT_LIMIT_MB = int(os.getenv("INGEST_RSS_SOFT_LIMIT_MB", "4096"))

# ---------- 重试 ----------
# 单文档尝试次数上限。超限后 status=failed，error_message / error_trace 留在行内，
# 前端可以直接展示"第几次、卡在哪个阶段、什么错"，不用翻日志。
MAX_ATTEMPTS = 3

# ---------- 后台模型调用的死线 ----------
# 汇总阶段的两次 LLM 调用（章节树、参考文献）必须有超时。
# 实测：模型端点在网络不畅时会连续退避重试，一次调用白等 31s，
# 参考文献那次（prompt 更长）等了 158s —— 整本书的解析有 1/5 时间耗在这。
# 超时就退到确定性启发式（按字号分层 / 按编号切分），结果差一点但任务能结束。
LLM_STRUCTURE_TIMEOUT_S = 45.0

# ---------- I/O ----------
# 下载/上传的分块大小。1MiB 是 MinIO multipart 的友好粒度。
IO_CHUNK_BYTES = 1024 * 1024
# SSE 服务端轮询间隔（毫秒）。太密会打满 SQLite 读，太疏前端进度条会跳。
PROGRESS_POLL_MS = 700
